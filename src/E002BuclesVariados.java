void main() {
    for (int i = 1; i <= 10; i++) {
        IO.print(i + " ");
    }

    IO.println();

    int i = 1;
    while (i <= 10) {
        IO.print(i + " ");
        i++;
    }

    IO.println();

    int a = 1;
    do {
        IO.print(a + " ");
        a++;
    } while (a <= 10);

    IO.println();

    for (int k = 2; k <= 20; k = k + 2) {
        IO.print(k + " ");
    }

    IO.println();

    int j = 2;

    while (j <= 20) {
        IO.print(j + " ");
        j = j + 2;
    }

    IO.println();

    int k = 2;
    do {
        IO.print(k + " ");
        k = k + 2;
    } while (k <= 20);
}