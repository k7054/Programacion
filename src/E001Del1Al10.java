void main() {
    for (int i = 1; i <= 10; i++) {
        IO.print(i + " ");
    }

    IO.println();

    int i = 1;
    while (i <= 10) {
        IO.print(i + " ");
        i++;
    }

    IO.println();

    int a = 1;
    do {
        IO.print(a + " ");
        a++;
    } while (a <= 10);

    IO.println();
}